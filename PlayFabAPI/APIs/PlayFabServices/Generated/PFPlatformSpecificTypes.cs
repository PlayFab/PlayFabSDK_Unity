    /// <summary>
    /// PFPlatformSpecificAwardSteamAchievementItem data model.
    /// </summary>
    public struct PFPlatformSpecificAwardSteamAchievementItem
    {
        /// <summary>
        /// Unique Steam achievement name.
        /// </summary>
        public string AchievementName;

        /// <summary>
        /// Unique PlayFab assigned ID of the user on whom the operation will be performed.
        /// </summary>
        public string PlayFabId;

        /// <summary>
        /// Result of the award attempt (only valid on response, not on request).
        /// </summary>
        public bool Result;

        internal unsafe PFPlatformSpecificAwardSteamAchievementItem(Interop.PFPlatformSpecificAwardSteamAchievementItem interop)
        {

            AchievementName = InteropWrapper.WrapperHelpers.InteropToString(interop.achievementName)!;

            PlayFabId = InteropWrapper.WrapperHelpers.InteropToString(interop.playFabId)!;

            Result = InteropWrapper.WrapperHelpers.InteropToBool(interop.result);

        }

        internal unsafe static void ToInterop(PFPlatformSpecificAwardSteamAchievementItem self, Interop.PFPlatformSpecificAwardSteamAchievementItem* interop, InteropWrapper.DisposableBuffer buffer)
        {
            *interop = default;

            InteropWrapper.WrapperHelpers.StringToInterop(self.AchievementName, &interop->achievementName, buffer);

            InteropWrapper.WrapperHelpers.StringToInterop(self.PlayFabId, &interop->playFabId, buffer);

            interop->result = InteropWrapper.WrapperHelpers.BoolToInterop(self.Result);

        }
    }

    /// <summary>
    /// PFPlatformSpecificAwardSteamAchievementRequest data model.
    /// </summary>
    public struct PFPlatformSpecificAwardSteamAchievementRequest
    {
        /// <summary>
        /// Array of achievements to grant and the users to whom they are to be granted.
        /// </summary>
        public PFPlatformSpecificAwardSteamAchievementItem[] Achievements;

        internal unsafe static void ToInterop(PFPlatformSpecificAwardSteamAchievementRequest self, Interop.PFPlatformSpecificAwardSteamAchievementRequest* interop, InteropWrapper.DisposableBuffer buffer)
        {
            *interop = default;

            InteropWrapper.WrapperHelpers.ArrayToInterop(self.Achievements, &interop->achievements, buffer, PFPlatformSpecificAwardSteamAchievementItem.ToInterop);
            interop->achievementsCount = (uint)self.Achievements.Length;

        }
    }

    /// <summary>
    /// PFPlatformSpecificAwardSteamAchievementResult data model.
    /// </summary>
    public struct PFPlatformSpecificAwardSteamAchievementResult
    {
        /// <summary>
        /// (Optional) Array of achievements granted.
        /// </summary>
        public PFPlatformSpecificAwardSteamAchievementItem[]? AchievementResults;

        internal unsafe PFPlatformSpecificAwardSteamAchievementResult(Interop.PFPlatformSpecificAwardSteamAchievementResult interop)
        {

            AchievementResults = (interop.achievementResults == null) ? null : InteropWrapper.WrapperHelpers.InteropToArray(*interop.achievementResults, interop.achievementResultsCount, elem => new PFPlatformSpecificAwardSteamAchievementItem(elem));

        }
    }

