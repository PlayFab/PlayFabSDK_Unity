    /// <summary>
    /// PFPlatformSpecificAndroidDevicePushNotificationRegistrationRequest data model. More information can
    /// be found on configuring your game for the Google Cloud Messaging service in the Google developer documentation,
    /// here: http://developer.android.com/google/gcm/client.html. The steps to configure and send Push Notifications
    /// is described in the PlayFab tutorials, here: https://docs.microsoft.com/gaming/playfab/features/engagement/push-notifications/quickstart.
    /// </summary>
    public struct PFPlatformSpecificAndroidDevicePushNotificationRegistrationRequest
    {
        /// <summary>
        /// (Optional) Message to display when confirming push notification.
        /// </summary>
        public string? ConfirmationMessage;

        /// <summary>
        /// Registration ID provided by the Google Cloud Messaging service when the title registered to receive
        /// push notifications (see the GCM documentation, here: http://developer.android.com/google/gcm/client.html).
        /// </summary>
        public string DeviceToken;

        /// <summary>
        /// (Optional) If true, send a test push message immediately after sucessful registration. Defaults to
        /// false.
        /// </summary>
        public bool? SendPushNotificationConfirmation;

        internal unsafe static void ToInterop(PFPlatformSpecificAndroidDevicePushNotificationRegistrationRequest self, Interop.PFPlatformSpecificAndroidDevicePushNotificationRegistrationRequest* interop, InteropWrapper.DisposableBuffer buffer)
        {
            *interop = default;

            if (self.ConfirmationMessage != null)
            {
                InteropWrapper.WrapperHelpers.StringToInterop(self.ConfirmationMessage, &interop->confirmationMessage, buffer);
            }

            InteropWrapper.WrapperHelpers.StringToInterop(self.DeviceToken, &interop->deviceToken, buffer);

            if (self.SendPushNotificationConfirmation != null)
            {
                interop->sendPushNotificationConfirmation = (byte*)buffer.AddBuffer(sizeof(byte));
                *interop->sendPushNotificationConfirmation = InteropWrapper.WrapperHelpers.BoolToInterop(self.SendPushNotificationConfirmation.Value);
            }

        }
    }

